"""
Cohort Retention Analytics Engine.

Transforms transactional timelines into structured customer retention matrices,
tracking user return rates, churn curves, and cohort lifetime revenue over time.
"""

from typing import Dict, Optional, Tuple
import numpy as np
import pandas as pd


class CohortEngine:
    """
    Computes monthly cohort retention matrices, customer counts, churn rates,
    and cohort revenue performance.
    """

    def __init__(self, transactions_df: pd.DataFrame):
        """
        Args:
            transactions_df: DataFrame with ['customer_id', 'order_id', 'order_date', 'total_amount'].
        """
        if transactions_df.empty:
            raise ValueError("Transactions DataFrame cannot be empty.")

        self.df = transactions_df.copy()
        self.df["order_date"] = pd.to_datetime(self.df["order_date"])

        self.cohort_counts: Optional[pd.DataFrame] = None
        self.retention_matrix: Optional[pd.DataFrame] = None
        self.revenue_matrix: Optional[pd.DataFrame] = None
        self.cohort_sizes: Optional[pd.Series] = None

    def _prepare_cohort_features(self) -> pd.DataFrame:
        """
        Derive cohort month, transaction month, and the cohort index (months elapsed).
        """
        df = self.df.copy()

        # Truncate order date to first day of the month
        df["order_month"] = df["order_date"].dt.to_period("M").dt.to_timestamp()

        # Find the earliest order month for each customer (acquisition cohort)
        cohort_map = df.groupby("customer_id")["order_month"].min().to_dict()
        df["cohort_month"] = df["customer_id"].map(cohort_map)

        # Calculate integer month difference
        # Cohort Index = (Year_diff * 12) + Month_diff
        year_diff = df["order_month"].dt.year - df["cohort_month"].dt.year
        month_diff = df["order_month"].dt.month - df["cohort_month"].dt.month
        df["cohort_index"] = year_diff * 12 + month_diff

        return df

    def compute_retention_matrix(self) -> Tuple[pd.DataFrame, pd.DataFrame, pd.Series]:
        """
        Build the monthly customer count matrix and percentage retention matrix.
        
        Returns:
            Tuple of:
            - cohort_counts: Raw active customer counts per cohort and month index.
            - retention_matrix: Percentage retention rate (0-100%) per cohort.
            - cohort_sizes: Initial customer count at Month 0 for each cohort.
        """
        df = self._prepare_cohort_features()

        # Group by cohort_month and cohort_index to count unique customers
        cohort_grouped = df.groupby(["cohort_month", "cohort_index"])["customer_id"].nunique().reset_index()

        # Pivot to tabular matrix format: rows = cohort_month, cols = cohort_index
        self.cohort_counts = cohort_grouped.pivot(
            index="cohort_month",
            columns="cohort_index",
            values="customer_id"
        )

        # Format row index strings as 'YYYY-MM'
        self.cohort_counts.index = self.cohort_counts.index.strftime("%Y-%m")

        # Month 0 size represents total acquired customers in that cohort
        self.cohort_sizes = self.cohort_counts.iloc[:, 0]

        # Calculate retention percentage: active customers / month 0 cohort size
        self.retention_matrix = self.cohort_counts.divide(self.cohort_sizes, axis=0) * 100.0
        self.retention_matrix = self.retention_matrix.round(2)

        return self.cohort_counts, self.retention_matrix, self.cohort_sizes

    def compute_revenue_matrix(self) -> pd.DataFrame:
        """
        Build the cohort revenue matrix tracking monetary spend across cohort months.
        
        Returns:
            DataFrame of monthly revenue generated by each cohort over time.
        """
        df = self._prepare_cohort_features()

        revenue_grouped = df.groupby(["cohort_month", "cohort_index"])["total_amount"].sum().reset_index()

        self.revenue_matrix = revenue_grouped.pivot(
            index="cohort_month",
            columns="cohort_index",
            values="total_amount"
        ).fillna(0.0)

        self.revenue_matrix.index = self.revenue_matrix.index.strftime("%Y-%m")
        self.revenue_matrix = self.revenue_matrix.round(2)

        return self.revenue_matrix

    def compute_cumulative_arpu_matrix(self) -> pd.DataFrame:
        """
        Compute Cumulative Average Revenue Per User (Cumulative ARPU / LTV curve)
        for each cohort across cohort age.
        """
        if self.revenue_matrix is None or self.cohort_sizes is None:
            self.compute_retention_matrix()
            self.compute_revenue_matrix()

        assert self.revenue_matrix is not None
        assert self.cohort_sizes is not None

        # Cumulative spend along cohort indices
        cum_revenue = self.revenue_matrix.cumsum(axis=1)
        # Divide by initial cohort size
        arpu_matrix = cum_revenue.divide(self.cohort_sizes, axis=0).round(2)
        return arpu_matrix

    def compute_churn_matrix(self) -> pd.DataFrame:
        """
        Compute customer churn rate matrix (100% - Retention Rate).
        """
        if self.retention_matrix is None:
            self.compute_retention_matrix()

        assert self.retention_matrix is not None
        churn_matrix = (100.0 - self.retention_matrix).round(2)
        # Month 0 churn is 0.0 by definition
        churn_matrix.iloc[:, 0] = 0.0
        return churn_matrix

    def get_retention_summary_kpis(self) -> Dict[str, float]:
        """
        Compute headline executive metrics:
        - Average Month 1 retention
        - Average Month 3 retention
        - Average Month 6 retention
        - Overall retention decay rate
        """
        if self.retention_matrix is None:
            self.compute_retention_matrix()

        assert self.retention_matrix is not None

        kpis = {}

        for month_idx in [1, 2, 3, 6, 12]:
            if month_idx in self.retention_matrix.columns:
                valid_vals = self.retention_matrix[month_idx].dropna()
                kpis[f"Avg_Month_{month_idx}_Retention_Pct"] = round(float(valid_vals.mean()), 2) if not valid_vals.empty else 0.0
            else:
                kpis[f"Avg_Month_{month_idx}_Retention_Pct"] = 0.0

        if self.cohort_sizes is not None:
            kpis["Total_Acquired_Customers"] = int(self.cohort_sizes.sum())
            kpis["Avg_Monthly_Cohort_Size"] = round(float(self.cohort_sizes.mean()), 1)

        return kpis

    def run_full_pipeline(self) -> Dict[str, pd.DataFrame]:
        """Execute all cohort calculations and return a dictionary of result matrices."""
        self.compute_retention_matrix()
        self.compute_revenue_matrix()
        arpu = self.compute_cumulative_arpu_matrix()
        churn = self.compute_churn_matrix()

        return {
            "cohort_counts": self.cohort_counts,
            "retention_matrix": self.retention_matrix,
            "revenue_matrix": self.revenue_matrix,
            "cumulative_arpu_matrix": arpu,
            "churn_matrix": churn
        }
